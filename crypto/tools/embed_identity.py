#!/usr/bin/env python3
"""Embed only the RISC-V client's credential and public trust anchor."""

from __future__ import annotations

import argparse
from pathlib import Path


def render_array(name: str, payload: bytes) -> str:
    rows = []
    for offset in range(0, len(payload), 12):
        rows.append("    " + ", ".join(f"0x{byte:02x}" for byte in payload[offset:offset + 12]))
    body = ",\n".join(rows)
    return f"static const uint8_t {name}[{len(payload)}] = {{\n{body}\n}};"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cert-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    cert_dir = args.cert_dir
    values = {
        "g_client_mldsa_cert": (cert_dir / "client_mldsa.crt").read_bytes(),
        "g_client_mldsa_key": (cert_dir / "client_mldsa.key").read_bytes(),
        "g_mldsa_ca_cert": (cert_dir / "pqc_mldsa_ca.crt").read_bytes(),
    }
    header = [
        "/* Generated by crypto/tools/embed_identity.py; do not edit. */",
        "#ifndef MLDSA_IDENTITY_H",
        "#define MLDSA_IDENTITY_H",
        "",
        "#include <stdint.h>",
        "",
        *[render_array(name, payload) + "\n" for name, payload in values.items()],
        "#endif /* MLDSA_IDENTITY_H */",
        "",
    ]
    args.output.write_text("\n".join(header), encoding="ascii")


if __name__ == "__main__":
    main()
